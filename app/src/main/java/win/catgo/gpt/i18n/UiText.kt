object UiText {
    @Volatile private var application: Context? = null
    @Volatile private var cached: Pair<String, Context>? = null
    private fun localized(context: Context): Context {
        val key = androidx.appcompat.app.AppCompatDelegate.getApplicationLocales().toLanguageTags() +
            "|" + context.resources.configuration.locales.toLanguageTags()
        cached?.takeIf { it.first == key }?.let { return it.second }
        return ContextCompat.getContextForLanguage(context).also { cached = key to it }
    }
    fun initialize(context: Context) { application = context.applicationContext }
    fun locale(context: Context): Locale =
        ContextCompat.getContextForLanguage(context).resources.configuration.locales[0]
    fun text(source: String): String {
        val context = application ?: return source
        val id = resources[source] ?: return source
        return localized(context).getString(id)
    }
